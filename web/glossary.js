function renderCard(key) {
  const t = get(key);
  if (!t) return null;
  const kv = [
    ['名称', t.n + (t.abbr && t.abbr !== t.n ? `（${t.abbr}）` : '')],
    ['正常范围', t.normal || '—'],
    ['含义', t.def || '—'],
    ['为什么重要', t.why || '—'],
  ];
  if (t.use) kv.push(['作用', t.use]);
  if (t.good) kv.push(['适应与优点', t.good]);
  if (t.bad) kv.push(['风险与禁忌', t.bad]);
  if (t.tip) kv.push(['用法要点', t.tip]);
  return { title: t.n, sub: t.abbr || '', kv };
}

function search(q) {
  ensureAutoCatalog();
  q = (q || '').trim();
  if (!q) return TERMS;
  const low = q.toLowerCase();
  return TERMS.filter(t => [
    t.n, t.alt, t.abbr, t.normal, t.def, t.why, t.use, t.good, t.bad, t.tip,
  ].some(v => (v || '').toLowerCase().includes(low)));
}

