let autoCatalogDone = false;
function ensureAutoCatalog() {
  if (autoCatalogDone) return;
  const hasSources = (root.CASEGEN && Array.isArray(root.CASEGEN.MODULES)) ||
    (root.SIGNS && typeof root.SIGNS.catalog === 'function') || root.LIFE_EXAMS || root.EXAMS;
  if (!hasSources) return;
  autoCatalogDone = true;
  const extra = autoCatalogTerms();
  if (!extra.length) return;
  for (const t of extra) TERMS.push(t);
  BY_KEY_BUILD();
}
