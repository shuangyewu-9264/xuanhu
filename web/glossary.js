/* ===== 自动收录：疾病 / 体征 / 查体 / 检查 =====
   数据来自 generator（病例模块）、signs（体征）、exams（查体与检查）。
   新增内容后无需手工补条目，术语表会自动跟上。 */
function autoCatalogTerms() {
  const out = [];
  const seen = new Set(TERMS.map(t => t.n));

  const CG = root.CASEGEN;
  if (CG && Array.isArray(CG.MODULES)) {
    for (const m of CG.MODULES) {
      if (!m.name || seen.has(m.name)) continue;
      seen.add(m.name);
      let goals = [];
      try { goals = m.goal || []; } catch (e) { goals = []; }
      out.push({
        n: m.name, tags: ['disease'], auto: true,
        def: '病例库中的诊断。',
        why: m.hint || '按主诉、查体与检查逐步确认；同名表现可能对应多个诊断。',
        tip: goals.length ? ('出院目标：' + goals.join('；')) : '',
      });
    }
  }

  const SG = root.SIGNS;
  const catalog = SG && (typeof SG.catalog === 'function' ? SG.catalog() : (SG.SIGNS || []));
  if (Array.isArray(catalog)) {
    for (const s of catalog) {
      if (!s.name || seen.has(s.name)) continue;
      seen.add(s.name);
      out.push({
        n: s.name, tags: ['sign'], auto: true,
        def: s.brief || s.name,
        why: s.causes ? ('常见原因：' + s.causes) : '由生命体征或化验推导出的体征，可作为排查线索。',
        tip: s.level === 'critical' ? '危急体征，需要立刻处理。' : '',
      });
    }
  }

  const X = root.LIFE_EXAMS || root.EXAMS;
  if (X) {
    for (const [key, kind] of [['EXAMS', '床旁查体'], ['TESTS', '辅助检查']]) {
      const group = X[key];
      if (!group) continue;
      for (const item of Object.values(group)) {
        if (!item.name || seen.has(item.name)) continue;
        seen.add(item.name);
        const cost = Number.isFinite(item.cost) ? ('约 ¥' + item.cost) : '';
        const ready = Number.isFinite(item.min) ? ('约 ' + item.min + ' 分钟出结果') : '';
        out.push({
          n: item.name, tags: ['exam'], auto: true,
          def: kind + '：' + (item.desc || ''),
          why: key === 'EXAMS'
            ? '床旁查体，不花钱、出结果快，是急诊首诊最主要的取证方式。'
            : '采样后需等待回报；结果与采样时刻的状态对应，必要时复查。',
          tip: [cost, ready].filter(Boolean).join(' · '),
        });
      }
    }
  }
  return out;
}

