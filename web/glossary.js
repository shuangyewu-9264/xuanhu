function effectSummary(eff) {
  if (!eff) return '';
  const parts = [];
  for (const [k, v] of Object.entries(eff)) {
    const label = EFFECT_LABELS[k] || k;
    if (typeof v !== 'number' || !v) continue;
    const up = v > 0;
    /* 感染负荷、抽搐、颅内压是"越低越好"的指标 */
    const good = ['infection', 'seizure', 'icp'].includes(k) ? !up : up;
    parts.push((up ? '↑' : '↓') + label + (good ? '' : '（不利）'));
  }
  return parts.join('、');
}
